export const HELPER_MILESTONES = [10, 25, 50, 100];

export function getHelperMilestoneMultiplier(owned: number): number {
  let mult = 1;
  for (const m of HELPER_MILESTONES) {
    if (owned >= m) mult *= 2;
  }
  return mult;
}
